def build_rows():
    header = ("id,exam,status,subdomain,subdomain_title,question,choice_a,choice_b,choice_c,"
              "choice_d,choice_e,choice_f,answer,explanation_a,explanation_b,explanation_c,"
              "explanation_d,explanation_e,explanation_f,lineage,sources,source_urls,"
              "source_answers,uncertain,answer_by,explanation_by,derived_from,updated_at,"
              "rechecked_at,recheck_note").split(",")
    ids = [question_id(q, [c for c, _ in ch]) for _, q, ch, _, _ in QUESTIONS]
    rows = [header]
    for i, (sub, q, choices, answer, uncertain) in enumerate(QUESTIONS):
        texts = [c for c, _ in choices] + [""] * (6 - len(choices))
        expl = [e for _, e in choices] + [""] * (6 - len(choices))
        derived = ids[i - 1] if i else ids[1]
        rows.append([
            ids[i], "pmle", "active", sub, SUBDOMAINS[sub], q, *texts, answer, *expl,
            "created", "created", f"docs/demo/demo-bank.csv#{i + 1}", f"created: {answer}",
            "TRUE" if uncertain else "FALSE", "llm", "llm", derived, UPDATED_AT, "", "",
        ])
    return rows


def main():
    rows = build_rows()
    assert len(rows) == 26, len(rows)
    assert len({r[0] for r in rows[1:]}) == 25
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="") as f:
        csv.writer(f, lineterminator="\r\n").writerows(rows)
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(rows) - 1} questions)")
    print(SECTION_WEIGHTS)


if __name__ == "__main__":
    main()
